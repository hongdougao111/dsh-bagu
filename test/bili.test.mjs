test('B站评论区真人语料零误拦', () => {
  const fails = [];
  for (const t of BILI) {
    const r = guard(t);
    if (!r.ok) fails.push({ t, line: r.line });
  }
  assert.deepEqual(fails, [], '误拦 ' + fails.length + ' 条:\n' +
    fails.map((f) => `「${f.t.slice(0, 40)}…」→ ${f.line}`).join('\n'));
});

test('B站反例要拦住', () => {
  const anti = '内容不错的呢，一定会火[打call][打call]期待新作品 能求个up互关么~~[打call]';
  const r = guard(anti);
  assert.equal(r.ok, false, '这种求互关+一定会火该拦');
});

test('引用套话不算用套话', () => {
  // 讨论「我记下了」这句话本身，不是自己说
  assert.equal(guard('评论区一水儿「我记下了」，反而把这毛病坐实了').ok, true);
  assert.equal(guard('翻了下自己前天留的评论，两条里就有一句「我记下了」').ok, true);
  // 直接说就是套话
  assert.equal(guard('我记下了').ok, false);
});

test('否定语境下的套话不算用', () => {
  assert.equal(guard('不要只说「受益匪浅」').ok, true);
  assert.equal(guard('别写「这条我认」').ok, true);
  // 真在拍马屁
  assert.equal(guard('受益匪浅').ok, false);
});

test('点评别人的套话不算自己用', () => {
  assert.equal(guard('一定会火＋求互关，雷踩得一个不落').ok, true);
  assert.equal(guard('这条建议当课后作业置顶').ok, true);
});
