test('贴吧真人语料零误拦', () => {
  const fails = [];
  for (const t of TIEBA) {
    const r = guard(t);
    if (!r.ok) fails.push({ t, line: r.line });
  }
  assert.deepEqual(fails, [], '误拦了 ' + fails.length + ' 条:\n' +
    fails.map((f) => `「${f.t}」→ ${f.line}`).join('\n'));
});

test('专名对举放过，抽象对举拦住', () => {
  // 「不是天理，是阿斯莫代」两边都是专名 → 对事实的纠正
  assert.equal(guard('一开头拦下双子的人就不是天理，是阿斯莫代').ok, true);
  assert.equal(guard('不是因为崩坏，是被策划削了').ok, true);

  // 「不是技术问题，而是认知问题」两边都是抽象概念 → 自造对立
  assert.equal(guard('这不是技术问题，而是认知问题。').ok, false);
  assert.equal(guard('问题不在于工具本身，而在于使用工具的人。').ok, false);
  assert.equal(guard('与其说是技术突破，不如说是思维方式的转变。').ok, false);
});

test('规则不能静默失效：直接调每条 test，不要靠 try/catch 兜着', () => {
  // 曾经踩过的坑：x 在 if 块里 const 声明，块外又引用，
  // 抛 ReferenceError 之后被 guard 的 try/catch 吞成「没命中」——
  // 规则整个失效，但 doestNotThrow 永远测不出来。
  // 所以这里绕过 guard，直接拿每条规则的 test 函数跑一遍。
  const cases = [
    '这不是技术问题，而是认知问题。',
    '一开头拦下双子的人就不是天理，是阿斯莫代',
    '不是',
    '不是A而是B',
    '',
    '？',
    '这条我认！首先态度要正，其次内容要实',
    'feat: 优化了用户模块的代码结构',
    '// 初始化计数器\nlet total = 0;',
  ];
  for (const reason of REASONS_FOR_TEST) {
    for (const t of cases) {
      let hit;
      assert.doesNotThrow(() => {
        hit = reason.test({ hits: { structures: [], aiWords: [], summary: [], fakeSignificance: [] }, synonyms: [], scores: {}, band: 'low' }, t, { repeatBar: 1 });
      }, `规则 ${reason.id} 在「${t}」上抛异常`);
      assert.equal(typeof hit, 'boolean', `规则 ${reason.id} 在「${t}」上返回了 ${typeof hit}，不是布尔`);
    }
  }
});
