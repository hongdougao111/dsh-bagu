import { guard } from '../lib/guard.js';

/**
 * 漏判率压测。跟 falserate.mjs 反向：
 * 这里全是 AI 最容易写出来的句子，看能拦多少。
 *
 * 漏了不致命（工具是止血带不是解药），但漏太多就等于没有。
 */

const SLOP = [
  // 客服腔
  '感谢分享！这个视频通过生动有趣的方式展示了相关内容，受益匪浅。',
  '这个视频整体节奏清晰，令人受益匪浅。',
  '希望对你有帮助，如有疑问欢迎交流。',
  '感谢您的内容，学到了很多。',
  '这期视频讲得很好，内容详实，值得一看。',

  // 套话开场
  '总之，这个方案可行。',
  '总的来说，我建议先检查配置。',
  '综上所述，这次改动具有重要意义。',
  '首先，我们需要明确目标。',

  // 对举
  '这不是技术问题，而是认知问题。',
  '问题不在于工具本身，而在于使用工具的人。',
  '与其说是技术突破，不如说是思维方式的转变。',

  // 空评价
  '这个功能非常强大，使用起来很方便。',
  '界面设计简洁大方，操作体验流畅。',
  '整体表现优秀，值得推荐。',

  // 结构腔
  '这个方案有三个优点：成本低、维护简单、扩展性好。',
  '通过整合资源、优化流程、提升效率，实现了目标。',
  '首先我们要明确目标；其次要拆解任务；最后要复盘总结。',

  // 八股词
  '这期视频的底层逻辑讲得很清楚。',
  '需要从多个维度深入剖析这个问题。',
  '这个产品的核心竞争力在于生态。',
  '我们要形成闭环，找到抓手，赋能业务。',

  // 三段并列
  '画面精美、配乐用心、内容扎实。',
  '速度快、占用低、功能全。',

  // 表态套话
  '说句实话，这个确实做得不错，不过我觉得还可以更好。',
  '客观来说，两边都有道理。',
  '客观地讲，这个方案值得一试。',

  // 过度礼貌
  '您好，感谢您的提问，我来为您解答这个问题。',
  '亲，这个商品很不错的哦。',

  // 先表态再夸（猫娘草稿法里说的那层骨架）
  '看到这个我坐直了，回头翻自己上一条评论，果然也沾了点客服味。',
  '不得不说，这个设计真的很用心。',
  '说真的，这个改动让我刮目相看。',

  // 鱼八股
  '这条我认，本鱼记下了。',
  '本鱼最喜欢的一句话就是这个。',
  '收到主人，本鱼这就去办。',
];

let caught = 0;
const MISSED = [];

for (const text of SLOP) {
  const r = guard(text);
  if (r.ok) MISSED.push(text);
  else caught++;
}

const rate = Math.round(caught / SLOP.length * 100);
console.log(`样本 ${SLOP.length} 条，拦住 ${caught} 条（${rate}%），漏 ${MISSED.length} 条\n`);
for (const m of MISSED) console.log(`❌ 漏：「${m}」`);
