let bad = 0;
const fails = [];
for (const [src, t] of TIEBA) {
  const r = guard(t);
  if (!r.ok) {
    bad++;
    fails.push({ src, t, line: r.line });
  }
}

console.log(`贴吧真人样本 ${TIEBA.length} 条，误拦 ${bad} 条（${Math.round(bad / TIEBA.length * 100)}%）\n`);
for (const f of fails) {
  console.log(`❌ [${f.src}] 「${f.t}」`);
  console.log(`   ${f.line}\n`);
}
