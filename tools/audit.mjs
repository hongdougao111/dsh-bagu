import { guard } from '../lib/guard.js';

/**
 * 严谨性检查：不是单元测试，是把真实场景过一遍，看有没有系统性误判。
 * 输出给人看，不做断言 —— 断言写死在 test/ 里，这里是探索。
 */

const SHOULD_BLOCK = [
  // DSH 会话场景
  ['会话-套话开头', '总的来说，这个方案有以下三个优点：首先成本低，其次维护简单，最后扩展性好。'],
  ['会话-空评价', '这个改动非常有价值，对项目具有重要意义。'],
  ['会话-对举', '这不是一个配置问题，而是一个架构问题。'],
  ['会话-同义', '我们需要优化流程，提升效率，增强体验。'],
  ['会话-总结尾巴', '综上所述，建议按这个方向推进。'],

  // B站评论区场景
  ['评论-客服腔', '感谢分享！这个视频通过生动有趣的方式展示了相关内容，受益匪浅。'],
  ['评论-空夸', '太棒了，真的很优秀，值得学习！'],
  ['评论-三段并列', '画面精美、配乐用心、内容扎实，三方面都做到了。'],
  ['评论-八股词', '这期视频的底层逻辑讲得很清楚。'],

  // QQ 机器人场景
  ['机器人-鱼八股', '这条我认，本鱼记下了。'],
  ['机器人-先表态', '说句实话，这个确实做得不错，不过我觉得还可以更好。'],
  ['机器人-过度礼貌', '您好，感谢您的提问，我来为您解答这个问题。'],
];

const SHOULD_PASS = [
  // DSH 会话
  ['会话-具体', '改完了，加了 §4。第七页那个表我删了，因为原来那三列一直是空的。'],
  ['会话-犹豫', '这个我不太确定，可能是缓存的问题，我先试试清一下。'],
  ['会话-短答', '行，我看看。'],
  ['会话-否定但不套', '这个方案我不太喜欢，太重了。'],

  // B站评论区
  ['评论-具体吐槽', '卖卡卖完了随便写了'],
  ['评论-带细节', '转场那里剪得挺流畅的，我看了一遍'],
  ['评论-接梗', '柯莱、迪卢克：演完戏我家人能复活吗'],
  ['评论-反问', '你没看明白我想说的。'],
  ['评论-短评', '就这？'],
  ['评论-口语', '我去，圣土化任务没做'],

  // QQ 机器人
  ['机器人-日常', '吃了，就一碗面，汤有点咸'],
  ['机器人-关心', '你今天睡够了吗？别又熬到三点。'],
  ['机器人-短句', '嗯，在呢。'],
];

let falseNeg = 0;
let falsePos = 0;

console.log('=== 该拦的 ===');
for (const [name, text] of SHOULD_BLOCK) {
  const r = guard(text);
  const mark = r.ok ? '❌ 漏' : '✅';
  if (r.ok) falseNeg++;
  console.log(`${mark} ${name.padEnd(14)} ${r.ok ? '（放过了）' : r.line}`);
}

console.log('\n=== 该放的 ===');
for (const [name, text] of SHOULD_PASS) {
  const r = guard(text);
  const mark = r.ok ? '✅' : '❌ 误拦';
  if (!r.ok) falsePos++;
  console.log(`${mark} ${name.padEnd(14)} ${r.ok ? '' : r.line}`);
}

console.log(`\n漏判 ${falseNeg} 条 · 误拦 ${falsePos} 条`);
console.log(`共 ${SHOULD_BLOCK.length + SHOULD_PASS.length} 条样本`);
