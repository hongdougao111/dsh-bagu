/**
 * 通用层：不分场景，凡是人写的话都成立。
 *
 * 下面前两层跟场景无关 —— README、微博、邮件、commit、review，
 * 都是在「一句话换个人说还成不成立」这一个判据上过的。
 *
 * 场景层只是补充：每个场景有自己长出来的套话，但那不是判断依据，
 * 只是提高命中率的加速器。
 */

/** 第二层：空转。说了一个动作，但没说做了什么。哪都适用。 */
export const HOLLOW_ACTIONS = [
  // 动词 + 宏观名词。改哪一行？没说。
  /(?:优化|提升|改善|增强|完善|强化|改进)了?[^，。！？\n]{0,8}(?:结构|性能|体验|流程|逻辑|质量|效率|可维护性|可读性|稳定性|兼容性|扩展性|可用性|合理性|规范性)/g,
  /(?:调整|修改|更新|变更)了?[^，。！？\n]{0,10}(?:相关|部分|若干|一些|整体|全部|必要|相应)/g,
  /(?:修复|解决|处理)了?(?:若干|多个|一些|部分|一系列|相关|已知)[^。！？\n]{0,8}(?:问题|bug|缺陷|错误|情况)?/gi,
  // 「进行了」开头的一律是空转
  /进行了?[^，。！？\n]{0,12}(?:处理|操作|调整|优化|改进|完善)/g,
  // 「使得/使其」句式
  /(?:使得?|令)[^，。！？\n]{0,12}(?:更加?|更)[^，。！？\n]{0,8}(?:清晰|简洁|友好|高效|稳定|合理)/g,
];

/**
 * 第二层补充：空形容词。能贴到任何产品/项目/方案上，就是在撑场面。
 * 「先进的」「高性能」「高可用」「灵活」「易用」「完善的」「全面的」
 */
export const HOLLOW_ADJECTIVES = [
  // 「具备/拥有 + 良好的 X」是空转的标准形状，X 填什么都行
  /(?:具备|拥有|具有)[^，。！？\n]{0,6}(?:良好|优秀|出色|卓越|强大|完善)的[^，。！？\n]{0,8}/g,
  // 「能够满足…需要/需求」——满足谁的需要？没说是谁
  /(?:能够?|可以|可)(?:满足|适应|支持)[^，。！？\n]{0,12}(?:需要|需求|要求|发展)/g,
  /(?:先进|领先|专业|成熟|完善|全面|丰富|强大|灵活|易用|高效|稳定|可靠|安全|优质|卓越|创新)(?:的)?(?:技术|架构|方案|体系|能力|功能|体验|服务|设计|平台|产品|支持|保障)/g,
  /(?:高|极)(?:性能|可用|并发|效率|质量|标准|精度|稳定)/g,
  /(?:多种|各类|全方位|一站式|集成化|模块化)[^，。！？\n]{0,12}(?:支持|方案|服务|能力|方式)/g,
];

/**
 * 第三层补充：学习/认可腔。评论区特有，但换到哪都是假学生。
 * 「学到了」「涨知识」「受益匪浅」「说得太对了」
 */
export const LEARNED_TONE = [
  /(?:学|涨)到了?[^，。！？\n]{0,4}(?:很多|不少|东西|知识)?/g,
  /(?:涨|长)(?:知识|见识|姿势)了?/g,
  /(?:受益|收获)(?:匪浅|颇多|良多|很大)/g,
  // 只认明确在拍马屁的形态。「你说得对但是我不听」是梗，不在此列。
  // 「讲得很好」「说得太对」都是拍马屁。「你说得对」不收（那是接梗/抬杠）。
  /(?:说得|讲得)(?:太|很|非常|真)(?:对|好|准)(?:了)?/g,
  /(?:非常|很|挺)(?:实用|有用|干货|有价值)/g,
  /希望(?:以后|下次|继续|多)[^，。！？\n]{0,8}(?:多发|更新|分享)/g,
];

/**
 * 代码注释：把代码本身念一遍。
 *
 * 来源：beagle style-criteria「Obvious Comments」、voku code-slop「comments-hygiene」。
 * 判据是「注释删掉之后，读代码能不能得到同样的信息」。能，就是废话。
 *
 * 注意：这条只认最明显的形态 —— 注释里出现「初始化/循环/遍历/返回/设置」
 * 这类把动作念一遍的动词。真正聪明的判断要读代码，正则做不到。
 */
export const CODE_COMMENT_NARRATION = [
  /^\s*\/\/\s*(?:初始化|循环|遍历|迭代|返回|设置|赋值|定义|声明|创建|获取|判断|检查)[^\n]{0,20}$/gm,
  /^\s*#\s*(?:initialize|loop|iterate|return|set|create|get|check|define)[^\n]{0,24}$/gim,
  /\/\/\s*end\s+(?:if|for|while|switch|function|class)\s*$/gim,
];

/**
 * 鸡汤/口号。微博、朋友圈、公众号开头重灾区。
 *
 * 判据跟别的不一样：这类句子的问题不在句式，在「它不求证」。
 * 「努力不一定会成功」——对，但跟什么都没说一样。
 * 「愿你所行皆坦途」——祝福，但没有一个具体的人。
 */
export const MOTIVATIONAL_SLOP = [
  /愿[你您][^。！？\n]{0,20}(?:皆|都|一切)[^。！？\n]{0,8}(?:坦途|美好|顺遂|如意|如愿)/g,
  /(?:新|崭新)的(?:一天|开始|一年|征程)[，,]?/g,
  /(?:早安|晚安|中午好)[！!，,]?\s*(?:新|今天|愿)/g,
  /(?:努力|坚持|奋斗|拼搏)[^。！？\n]{0,10}(?:不一定|就会|才能|才会)/g,
  /(?:加|一起)?油[！!]/g,
  /(?:所行|所遇|所见|所得)[^。！？\n]{0,6}(?:皆|都)/g,
  /(?:每一个|每一天)[^。！？\n]{0,10}(?:值得|都)(?:被|是)/g,
];

/** 第三层：万能话。放到任何语境都通顺，等于什么都没说。 */
export const UNIVERSAL_FILLER = [
  /(?:随着|在)[^，。！？\n]{0,10}(?:的)?(?:发展|进步|普及|到来|推动)/g,
  /(?:在)?(?:当今|现在|如今)[^，。！？\n]{0,6}(?:时代|社会|环境|背景)/g,
  /众所周知[，,]?/g,
  /(?:值得|需要)(?:一提|注意|强调|指出)的?是/g,
  /(?:不仅|不只)(?:仅)?[^，。！？\n]{0,16}(?:更|还|而且)/g,
];
