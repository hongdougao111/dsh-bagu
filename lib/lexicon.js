/**
 * PR 描述的模板骨架。命中两行以上就不像人写的。
 * 常见于自动生成的 PR：## 概述 / ## 改动 / ## 影响
 */
export const GIT_TEMPLATE_ROWS = [
  /^#{1,4}\s*(概述|背景|改动|变更|影响|测试|备注|检查项|Checklist)\s*$/gm,
  /^-\s*\[(?:x| )\]\s*(?:已|未)?(?:测试|验证|更新|添加)/gm,
  /^(?:本|该)(?:PR|pr|次改动)(?:优化|调整|新增|修复|重构)/gm,
];

/** 数 PR 模板骨架命中了几行（不是几个正则命中，是几行）。 */
export function countTemplateRows(text) {
  const src = String(text ?? '');
  let n = 0;
  for (const re of GIT_TEMPLATE_ROWS) {
    const m = src.match(re);
    if (m) n += m.length;
  }
  return n;
}

